/** Fill a text: {name} from vars; a [one, other] pair picks by vars.n. */
export function fill(text, vars = {}) {
    if (Array.isArray(text)) text = vars.n == 1 ? text[0] : text[1];
    return String(text ?? "").replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
}
